def progress(a: RoleAssignment, passkey: dict[str, Any] | None, signed_in: datetime | None) -> str:
    """Where an invitee is: INVITED -> PASSKEY_CREATED -> SIGNED_IN -> ACTIVE (accepted)."""
    if a.status is RoleStatus.REVOKED:
        return "REVOKED"
    if a.status is not RoleStatus.INVITED:
        return a.status.value
    if signed_in is not None and passkey:
        return "SIGNED_IN"
    return "PASSKEY_CREATED" if passkey else "INVITED"


@router.get(
    "/v1/tenant/members",
    dependencies=[Depends(matrix_gate("a.list-active-members-and-assigned-roles", Mode.READ))],
)
async def read_members(request: Request, caller: CallerDep) -> dict[str, Any]:
    async with tenant_transaction(request_engine(request), caller.ctx) as conn:
        await _require_role(conn, caller)
        items = await store.roles(conn, live_only=False)
        ids = sorted({a.principal_id for a in items})
        keys = await passkey_summary(conn, ids)
        seen = await last_sign_in(conn, ids)
        refs = await people.person_refs(conn, ids)
    out = []
    for a in items:
        pk = keys.get(a.principal_id)
        at = seen.get(a.principal_id)
        signed_in = at if isinstance(at, datetime) else None
        out.append(
            {
                **role_view(a),
                "person": refs[a.principal_id].view(),
                "passkeys": int(pk["passkeys"]) if pk else 0,  # type: ignore[call-overload]
                "passkey_registered_at": _iso(pk["first_at"]) if pk else None,  # type: ignore[arg-type]
                "last_sign_in_at": _iso(signed_in),
                "progress": progress(a, pk, signed_in),
            }
        )
    return {"items": out}


