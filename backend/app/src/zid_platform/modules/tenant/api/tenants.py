"""Tenant lifecycle and administration API (ZID-OVERLAY-001 §2-4, §26; G-W0; CR-015).

    POST /v1/tenants                              create a DRAFT tenant (signup-tenant principal)
    GET  /v1/tenant                               the caller's tenant and the caller's roles
    GET  /v1/tenant/transitions                   lifecycle history            (OWNER/ADMIN)
    GET  /v1/tenant/configuration-revisions       configuration history        (OWNER/ADMIN)
    GET  /v1/tenant/members                       role assignments             (OWNER/ADMIN)
    POST /v1/tenant/members                       invite MEMBER/ADMIN          tenant.member.manage
    POST /v1/tenant/members/me:accept             the invited principal accepts
    POST /v1/tenant/members/{id}:revoke           tenant.member.manage
    POST /v1/tenant/members/{id}:reissue          a fresh enrollment link    tenant.member.manage
    POST /v1/tenant/owners                        tenant.owner.change + second administrator
    POST /v1/tenant/owners/{principal}:remove     tenant.owner.change + second administrator
    POST /v1/tenant:suspend                       tenant.lifecycle.manage (R3; the safer direction)
    POST /v1/tenant:resume                        tenant.lifecycle.manage + second administrator
    POST /v1/tenant:offboard                      tenant.lifecycle.manage + second administrator

The tenant is always the caller's (server-derived, INV-13); the only exception is creation, where
the new tenant id is generated by the server. Reads of the tenant's own lifecycle are open to its
OWNER/ADMIN roles (including the pending bootstrap OWNER, who has no authority yet); every change
goes through the PDP.
"""

