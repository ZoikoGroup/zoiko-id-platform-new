@router.post("/v1/tenants", status_code=201)
async def create_tenant(
    body: TenantCreate,
    request: Request,
    caller: CallerDep,
    idempotency_key: Annotated[str, Header(alias="Idempotency-Key")],
) -> dict[str, Any]:
    signup = getattr(request.app.state, "tenant_bootstrap_tenant_id", None)
    if not signup:
        raise http(TenantError("TENANT_BOOTSTRAP_DISABLED", "Tenant creation is not enabled here."))
    if str(caller.ctx.tenant_id) != str(signup):
        raise http(
            TenantError("TENANT_BOOTSTRAP_DISABLED", "Tenants are created from the signup tenant.")
        )
    if caller.actor is not None:
        raise http(TenantError("TENANT_OWNER_UNAUTHORIZED", "Creators act only as themselves."))
    if caller.authn.level < 2:
        raise ZidError(
            "STEP_UP_REQUIRED",
            "Creating a tenant needs a phishing-resistant authentication (AAL-Z2).",
            http_status=403,
        )
    creator = _principal(caller)
    console = getattr(request.app.state, "tenant_console", None)
    scope = Scope(caller.ctx.tenant_id or "", caller.client_id, "POST /v1/tenants")
    async with tenant_transaction(request_engine(request), caller.ctx) as conn:
        stored = await begin(
            conn, scope=scope, key=idempotency_key, payload=body.model_dump(mode="json")
        )
        if stored is not None:
            return dict(stored.body)
        try:
            result = await service.bootstrap_tenant(
                conn,
                creating_tenant_id=caller.ctx.tenant_id or "",
                creator_principal_id=creator,
                display_name=body.display_name,
                tenant_slug=body.tenant_slug,
                deployment_mode=body.deployment_mode,
                home_cell_id=getattr(request.app.state, "home_cell", None) or "local-1",
                console=service.ConsoleClient(*console) if console else None,
            )
        except TenantError as e:
            raise http(e) from e
        out = {
            "tenant": tenant_view(result.tenant),
            "owner_principal_id": result.owner_principal_id,
            "owner_role_status": RoleStatus.PENDING_VERIFICATION.value,
            "enrollment_ticket": result.enrollment_ticket,  # shown once
            "enrollment_ticket_expires_at": _iso(result.ticket_expires_at),
            "console_client_id": result.console_client_id,
            "next": "Enroll a passkey with the ticket, then submit the organization for "
            "verification (POST /v1/onboarding/organization).",
        }
        # The replayed response never contains the ticket again (it is a credential).
        await complete(
            conn,
            scope=scope,
            key=idempotency_key,
            status=201,
            body={**out, "enrollment_ticket": None},
        )
    return out


