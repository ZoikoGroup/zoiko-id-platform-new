"""Render the Prometheus rule file from the service catalogue (ZID-SRE-001 §5-6; G-W8).

    python -m zid_platform.ops_export          # rewrites deploy/observability/prometheus/rules/zid-slo.yaml

CI (`test_operations_catalogue.py`) fails if the committed rules drift from the catalogue, so an
SLO or alert change is always a reviewed diff of both files.
"""

from __future__ import annotations

from pathlib import Path

import yaml

from zid_platform.modules.operations.application.rules import render_rules
from zid_platform.modules.operations.ports import service_catalogue

REPO = Path(__file__).resolve().parents[4]
RULES_FILE = REPO / "deploy" / "observability" / "prometheus" / "rules" / "zid-slo.yaml"
RUNBOOK_BASE = "docs/runbooks"  # repo-relative; Alertmanager templates prefix the source host
HEADER = "# GENERATED by `python -m zid_platform.ops_export` from backend/config/operations/service-catalogue.yaml. Do not edit.\n"


def rendered() -> str:
    rules = render_rules(service_catalogue(), runbook_base=RUNBOOK_BASE)
    return HEADER + yaml.safe_dump(rules, sort_keys=False, width=200)


def main() -> None:
    RULES_FILE.parent.mkdir(parents=True, exist_ok=True)
    RULES_FILE.write_text(rendered(), encoding="utf-8")
    print(f"wrote {RULES_FILE}")


if __name__ == "__main__":
    main()
