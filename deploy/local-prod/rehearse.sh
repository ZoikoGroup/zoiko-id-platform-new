#!/usr/bin/env bash
# Local rehearsal of the production deployment on VMs. See README.md. Run from Git Bash (Windows) or any POSIX shell with Docker.
#   ./rehearse.sh up [--rebuild]   build images if missing, set up databases, keys, secrets and the event platform, start everything
#   ./rehearse.sh status | verify | logs [service] | unseal | keys <status|public|rotate-signing|rewrap ...> | down | reset
set -euo pipefail
export MSYS_NO_PATHCONV=1   # Git Bash on Windows must not rewrite container paths such as /zid/master_key
cd "$(dirname "$0")"
HERE="$PWD"
ROOT="$(cd ../.. && pwd)"
# relative: this script runs from its own folder. .env (generated passwords) and .env.smtp (your real SMTP provider) feed the compose file.
compose() {
  local f=(-f docker-compose.yml) e
  # optional, gitignored local additions (for example catching email in Mailpit): local-config/docker-compose.*.yml
  for e in local-config/docker-compose.*.yml; do [ -f "$e" ] && f+=(-f "$e"); done
  for e in .env .env.smtp .env.operator; do [ -f "$e" ] && f+=(--env-file "$e"); done
  docker compose "${f[@]}" "$@"
}
say() { printf '\n== %s\n' "$*"; }

build_images() {
  local force="${1:-}"
  if [ "$force" = "--rebuild" ] || ! docker image inspect zid/platform:prodlocal >/dev/null 2>&1; then
    say "building the backend image (backend/Dockerfile, runtime target: non-root, no build tools)"
    docker build -t zid/platform:prodlocal ../../backend
  fi
  if [ "$force" = "--rebuild" ] || ! docker image inspect zid/operator:prodlocal >/dev/null 2>&1; then
    say "building the operator console image (the same Dockerfile, APP=operator)"
    docker build --build-arg APP=operator -t zid/operator:prodlocal ../../frontend
  fi
  if [ "$force" = "--rebuild" ] || ! docker image inspect zid/web:prodlocal >/dev/null 2>&1; then
    say "building the web image (frontend/Dockerfile: npm ci, next build, standalone output)"
    docker build -t zid/web:prodlocal ../../frontend
  fi
}

# .env holds generated passwords for THIS rehearsal only (gitignored). Production keeps them outside the repository.
# There are deliberately no signing keys here: they are created in the database on first start (ZID_KEY_PROVIDER=db).
make_env() {
  [ -f .env ] || { echo "# Generated by rehearse.sh for the local rehearsal only. Never reuse these anywhere real." > .env; chmod 600 .env 2>/dev/null || true; }
  local n
  for n in ZID_PG_ADMIN_PASSWORD ZID_OWNER_PASSWORD ZID_RUNTIME_PASSWORD ZID_WORKER_PASSWORD ZID_RELAY_PASSWORD            ZID_OPENBAO_DB_PASSWORD ZID_SPICEDB_DB_PASSWORD ZID_SPICEDB_PRESHARED_KEY ZID_VALKEY_PASSWORD; do
    grep -q "^$n=" .env || { echo "generating $n"; echo "$n=$(openssl rand -hex 16)" >> .env; }
  done
}

# Email goes through a real SMTP provider, never a catcher. .env.smtp (gitignored) holds, one per line:
#   ZID_SMTP_HOST=smtp.example.com  ZID_SMTP_PORT=587  ZID_SMTP_USERNAME=...  ZID_EMAIL_FROM="Zoiko iD <no-reply@example.com>"
#   ZID_SMTP_PASSWORD_SRC=/path/to/a/file/holding/the/smtp/password        (read from your machine, copied to the secrets volume)
require_smtp() {
  local n missing=""
  [ -f .env.smtp ] || { echo "!! .env.smtp is missing: create it with ZID_SMTP_HOST, ZID_SMTP_PORT, ZID_SMTP_USERNAME, ZID_EMAIL_FROM and ZID_SMTP_PASSWORD_SRC (see rehearse.sh)"; exit 1; }
  for n in ZID_SMTP_HOST ZID_SMTP_PORT ZID_SMTP_USERNAME ZID_EMAIL_FROM ZID_SMTP_PASSWORD_SRC; do
    grep -q "^$n=." .env.smtp || missing="$missing $n"
  done
  [ -z "$missing" ] || { echo "!! .env.smtp is missing:$missing"; exit 1; }
  SMTP_SRC="$(grep -E '^ZID_SMTP_PASSWORD_SRC=' .env.smtp | head -1 | cut -d= -f2- | tr -d '"')"
  command -v cygpath >/dev/null 2>&1 && SMTP_SRC="$(cygpath -u "$SMTP_SRC")"
  [ -s "$SMTP_SRC" ] || { echo "!! the SMTP password file named by ZID_SMTP_PASSWORD_SRC does not exist or is empty"; exit 1; }
}

# The operator account (email and password sign-in; no passkey). .env.operator (gitignored) holds ZID_OPERATOR_EMAIL, ZID_OPERATOR_PASSWORD,
# ZID_OPERATOR_TENANT_ID and ZID_OPERATOR_BOOTSTRAP_PRINCIPAL_ID. The migrate step creates the account from them.
require_operator() {
  local n missing=""
  [ -f .env.operator ] || { echo "!! .env.operator is missing (see rehearse.sh)"; exit 1; }
  for n in ZID_OPERATOR_EMAIL ZID_OPERATOR_PASSWORD ZID_OPERATOR_TENANT_ID ZID_OPERATOR_BOOTSTRAP_PRINCIPAL_ID; do
    grep -q "^$n=." .env.operator || missing="$missing $n"
  done
  [ -z "$missing" ] || { echo "!! .env.operator is missing:$missing"; exit 1; }
}

envval() { grep -E "^$1=" .env | head -1 | cut -d= -f2-; }
set_env() { grep -v "^$1=" .env > .env.tmp || true; echo "$1=$2" >> .env.tmp; mv .env.tmp .env; }

psql_admin() { compose exec -T postgres psql -v ON_ERROR_STOP=1 -U postgres "$@"; }
tools() { compose run --rm --no-deps tools "$@"; }

wait_for() { # url label seconds
  local i=0
  until curl -fsS --max-time 4 -o /dev/null "$1" 2>/dev/null; do
    i=$((i + 2)); [ "$i" -ge "$3" ] && { echo "!! $2 did not become ready in $3 s ($1)"; return 1; }; sleep 2
  done
  echo "ok  $2"
}

database_setup() {
  say "databases zid_cell (the one platform database), openbao and spicedb; roles owner, runtime, worker (the production guide's step 3)"
  psql_admin -d postgres -tAc "SELECT 1 FROM pg_database WHERE datname='zid_cell'" | grep -q 1 \
    || psql_admin -d postgres -c "CREATE DATABASE zid_cell"
  psql_admin -d zid_cell -v owner_pw="$(envval ZID_OWNER_PASSWORD)" -v runtime_pw="$(envval ZID_RUNTIME_PASSWORD)" \
    -v worker_pw="$(envval ZID_WORKER_PASSWORD)" -f - < "$ROOT/deploy/gcp/db/01_roles.sql" >/dev/null
  psql_admin -d postgres -v openbao_pw="$(envval ZID_OPENBAO_DB_PASSWORD)" -v spicedb_pw="$(envval ZID_SPICEDB_DB_PASSWORD)" -f - < openbao_db.sql >/dev/null
  # OpenBao's table (its PostgreSQL storage backend), created as its own role
  compose exec -T postgres psql -v ON_ERROR_STOP=1 -U openbao -d openbao >/dev/null <<'SQL'
CREATE TABLE IF NOT EXISTS openbao_kv_store (
  parent_path TEXT COLLATE "C" NOT NULL, path TEXT COLLATE "C", key TEXT COLLATE "C", value BYTEA,
  CONSTRAINT pkey PRIMARY KEY (path, key));
CREATE INDEX IF NOT EXISTS parent_path_idx ON openbao_kv_store (parent_path);
SQL
  say "namespaces, as the owner role"
  compose exec -T postgres psql -v ON_ERROR_STOP=1 -U zid_owner -d zid_cell -f - < "$ROOT/backend/database/schemas/001_cell_schemas.sql" >/dev/null
  compose exec -T postgres psql -v ON_ERROR_STOP=1 -U zid_owner -d zid_cell -f - < "$ROOT/backend/database/schemas/001_global_schemas.sql" >/dev/null
}

grants() {
  say "privileges for the runtime and worker roles; the relay's own role (re-run after every migration that adds a schema)"
  psql_admin -d zid_cell -f - < "$ROOT/deploy/gcp/db/02_grants.sql" >/dev/null
  psql_admin -d zid_cell -v relay_pw="$(envval ZID_RELAY_PASSWORD)" -f - < "$ROOT/deploy/gcp/db/04_relay_role.sql" >/dev/null
}

# The files the processes read from the secrets volume: on a real VM, root-only files placed by a person.
secret_files() {
  say "master key and SMTP password (files on the secrets volume)"
  compose run --rm init-volumes >/dev/null
  if ! tools sh -c 'test -s /zid/master_key'; then
    tools python -m zid_platform.entrypoints.keys init-master --file /zid/master_key
  fi
  # the SMTP password is copied in on every start, so a changed password takes effect; it is never printed or logged
  compose run --rm -T --no-deps tools sh -c 'cat > /zid/smtp_password && chmod 600 /zid/smtp_password' < "$SMTP_SRC"
}

bao() { compose exec -T -e BAO_ADDR=http://127.0.0.1:8200 ${BAO_TOKEN:+-e BAO_TOKEN="$BAO_TOKEN"} openbao bao "$@"; }
# `bao status` exits 2 while sealed, which would fail a pipeline under pipefail: read its output first
bao_status() { bao status -format=json 2>/dev/null || true; }

openbao_unseal() {
  [ -f .openbao-init.json ] || return 0
  local key; key="$(sed -n 's/.*"unseal_keys_b64": *\[ *"\([^"]*\)".*/\1/p' .openbao-init.json | tr -d '\n' | head -1)"
  [ -n "$key" ] || key="$(tr -d '\n ' < .openbao-init.json | sed -n 's/.*"unseal_keys_b64":\["\([^"]*\)".*/\1/p')"
  bao operator unseal "$key" >/dev/null
}

openbao_setup() {
  say "OpenBao: init, unseal, policy and the application's token (data lives in PostgreSQL)"
  compose up -d openbao
  local i=0
  until [ "$(bao_status | grep -c '"initialized"')" -ge 1 ]; do
    i=$((i + 2)); [ "$i" -ge 60 ] && { echo "!! OpenBao did not start"; return 1; }; sleep 2
  done
  if ! bao_status | grep -q '"initialized": *true'; then
    # one share for the rehearsal; a real deployment uses 5 shares with a threshold of 3, held by different people
    bao operator init -key-shares=1 -key-threshold=1 -format=json > .openbao-init.json
    chmod 600 .openbao-init.json 2>/dev/null || true
    echo "  initialised; unseal key and root token saved in .openbao-init.json (gitignored; custodians hold these in real life)"
  fi
  if bao_status | grep -q '"sealed": *true'; then openbao_unseal; fi
  local root; root="$(tr -d '\n ' < .openbao-init.json | sed -n 's/.*"root_token":"\([^"]*\)".*/\1/p')"
  if ! tools sh -c 'test -s /zid/openbao_token'; then
    BAO_TOKEN="$root" bao secrets list -format=json 2>/dev/null | grep -q '"secret/"' || BAO_TOKEN="$root" bao secrets enable -path=secret kv-v2 >/dev/null
    printf 'path "secret/data/*" { capabilities = ["create","read","update","delete","list"] }\npath "secret/metadata/*" { capabilities = ["list","read","delete"] }\n' \
      | BAO_TOKEN="$root" bao policy write zid - >/dev/null
    local app; app="$(BAO_TOKEN="$root" bao token create -policy=zid -period=720h -orphan -format=json | tr -d '\n ' | sed -n 's/.*"client_token":"\([^"]*\)".*/\1/p')"
    compose run --rm --no-deps -T -e APP_TOKEN="$app" tools sh -c 'printf %s "$APP_TOKEN" > /zid/openbao_token && chmod 600 /zid/openbao_token'
    echo "  application token written to the secrets volume (periodic, policy zid: secret/* only)"
  fi
}

up() {
  require_smtp  # fail before anything starts if the real SMTP settings are missing
  require_operator
  [ -f idv-policies.local.yaml ] || { echo "!! idv-policies.local.yaml is missing: the approved markets for identity checks (a test policy locally; see the identity owner pack)"; exit 1; }
  build_images "${1:-}"
  make_env
  say "starting postgres, valkey and redpanda"
  compose up -d postgres valkey redpanda
  until [ "$(docker inspect -f '{{.State.Health.Status}}' "$(compose ps -q postgres)" 2>/dev/null)" = healthy ]; do sleep 2; done
  database_setup
  secret_files
  openbao_setup
  say "migrate, as the owner role"
  compose run --rm migrate
  grants
  if [ -z "$(envval ZID_REGISTRATION_TENANT_ID)" ]; then
    say "registration tenant (person-first sign-up)"
    local line
    line="$(compose run --rm migrate python -m zid_platform.entrypoints.seed_registration_tenant --apply | grep '^ZID_REGISTRATION_TENANT_ID=' | head -1)"
    set_env ZID_REGISTRATION_TENANT_ID "${line#ZID_REGISTRATION_TENANT_ID=}"
  fi
  say "starting the cell (it also serves the global plane), worker, event relay and consumer, and the web console"
  compose up -d --remove-orphans ocr face clamd cell worker outbox-relay consumer web operator
  wait_for "http://localhost:8000/health/ready" "cell API" 300
  wait_for "http://localhost:3000/" "web console" 300
  wait_for "http://localhost:3100/sign-in" "operator console" 300
  say "up"
  echo "  web console   http://localhost:3000"
  echo "  operator      http://localhost:3100   (email and password; no passkey)"
  echo "  identity      photo service (ocr) and malware scanner (clamd) run inside the stack; clamd takes about 3 minutes to load its signatures"
  echo "  cell API      http://localhost:8000/docs"
  echo "  email         sent through your SMTP provider (.env.smtp); nothing is caught locally"
  echo "  next:         ./rehearse.sh verify"
}

verify() {
  say "health"
  for u in 8000/health/ready 3000/ 3100/sign-in; do printf '  %-26s' "$u"; curl -s -o /dev/null --max-time 15 -w '%{http_code}\n' "http://localhost:$u" || true; done
  say "database roles (owner and runtime must not bypass row-level security)"
  psql_admin -d zid_cell -Atc "select rolname, rolsuper, rolbypassrls from pg_roles where rolname like 'zid_%' or rolname='openbao' order by 1"
  say "keys in the database (no material is shown; every row must hold wrapped material)"
  tools env ZID_CELL_DATABASE_URL="postgresql+asyncpg://zid_runtime:$(envval ZID_RUNTIME_PASSWORD)@postgres:5432/zid_cell" \
    python -m zid_platform.entrypoints.keys status
  say "the master key is not in the database"
  psql_admin -d zid_cell -Atc "select count(*) from keys.key_version where wrapped is not null and position('PRIVATE KEY' in convert_from(wrapped,'SQL_ASCII')) > 0" | sed 's/^/  rows holding a PEM in the clear: /'
  say "OpenBao: sealed? and a secret written and read back through the platform's own client"
  bao_status | grep -E '"(initialized|sealed|storage_type)"' | sed 's/^/  /'
  local root; root="$(tr -d '\n ' < .openbao-init.json | sed -n 's/.*"root_token":"\([^"]*\)".*/\1/p')"
  BAO_TOKEN="$root" bao kv put -mount=secret rehearsal/smoke value=read-back-ok >/dev/null
  tools python -c "
from zid_crypto.secret_broker import OpenBaoSecretBroker
b = OpenBaoSecretBroker('http://openbao:8200', mount='secret', token=lambda: open('/zid/openbao_token').read().strip())
print('  broker read:', b.get('rehearsal/smoke'))"
  say "event platform: topics on Kafka (created when the relay publishes)"
  compose exec -T redpanda rpk topic list 2>/dev/null | sed 's/^/  /' | head -12
  say "outbox: events waiting vs published"
  psql_admin -d zid_cell -Atc "select count(*) filter (where published_at is null), count(*) filter (where published_at is not null) from events.outbox_event" | sed 's/^/  unpublished|published: /'
}

case "${1:-}" in
  up) up "${2:-}" ;;
  status) compose ps ;;
  verify) verify ;;
  unseal) compose up -d openbao; sleep 3; openbao_unseal; echo "openbao unsealed" ;;
  keys) shift; tools env ZID_CELL_DATABASE_URL="postgresql+asyncpg://zid_runtime:$(envval ZID_RUNTIME_PASSWORD)@postgres:5432/zid_cell" python -m zid_platform.entrypoints.keys "$@" ;;
  logs) shift; compose logs --tail 80 "$@" ;;
  down) compose down ;;
  reset) compose down -v; rm -f .env .openbao-init.json; echo "all rehearsal data and generated secrets removed" ;;
  *) sed -n 2,4p "$0"; exit 2 ;;
esac
